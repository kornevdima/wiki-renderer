import "server-only";

import { tenantInitials } from "@/components/ui/tenant-logo";
import { env } from "@/lib/env";

/**
 * The app's branding, from the environment. By default the app is "Wiki Renderer" with the "WR" mark on the ESG background (US-289). A deployment such as a company vault sets its own name, product line, initials or logo.
 * The values are merged into the `brand.*`, `readerShell.brandProduct` and `documentTitle.suffix` messages by
 * `src/i18n/request.ts`, so every screen that shows the brand picks them up without its own wiring.
 */
export interface Branding {
  name: string;
  product: string;
  initials: string;
  tone: "indigo" | "deep" | "glow";
  /** The logo route when `BRAND_LOGO` names a file, the default WR mark when nothing is branded, else "" (the initials are drawn). */
  logo: string;
  titleSuffix: string;
}

export const BRAND_LOGO_ROUTE = "/api/brand/logo";

/**
 * The default mark (US-289): "WR" on the ESG background, a static file from `public/` generated by `scripts/make-mark.mjs`. It stands
 * in for the TenantLogo's initials only while nothing is branded: no `BRAND_LOGO`, no `BRAND_INITIALS`, and the default `BRAND_NAME`
 * (a company name with no initials still gets its own initials, not "WR"). The tab icons (`src/app/icon.*`, `favicon.ico`) are always
 * the WR mark: no `BRAND_*` setting reaches them today.
 */
export const DEFAULT_MARK_ROUTE = "/wr-mark.svg";
export const DEFAULT_BRAND_NAME = "Wiki Renderer";

export function branding(): Branding {
  const name = env.BRAND_NAME;
  const logo = env.BRAND_LOGO !== undefined ? BRAND_LOGO_ROUTE : env.BRAND_INITIALS === undefined && name === DEFAULT_BRAND_NAME ? DEFAULT_MARK_ROUTE : "";
  return {
    name,
    product: env.BRAND_PRODUCT,
    initials: tenantInitials(name, env.BRAND_INITIALS),
    tone: env.BRAND_TONE,
    logo,
    titleSuffix: env.BRAND_TITLE ?? name,
  };
}
